#!/usr/bin/env python3
"""FSRCNNX for Qt Quick: igv's mpv user shader, made into ShaderEffect passes.

FSRCNNX_x2_8-0-4-1.glsl (LGPL-3.0, (c) 2017-2021 igv) is a small trained
network written as mpv hooks on LUMA: thirteen passes at the frame's own
size, each a handful of convolutions over the last ones' textures, then an
aggregation that spreads four values a texel into the 2x picture. mpv runs
hooks; Qt Quick runs ShaderEffects over ShaderEffectSources. This writes

  * fsrcnnx_NN.frag — one per pass, the hook's own body untouched, its
    `NAME_texOff(off)` reads made into samplers one texel `pt` apart. LUMA
    is not a texture here: the first passes read the frame's RGB and take
    its BT.709 luma where the hook read LUMA.
  * ../Fsrcnnx.qml — the passes wired in order: each pass an effect at the
    frame's size, captured into an RGBA16F texture (the features go
    negative), each BIND the latest SAVE of that name.

The aggregation is fsrcnnx_compose.frag, written by hand, because it is also
where the colour comes back: the 2x luma replaces the frame's own, keeping
its chroma. Run build.sh afterwards to bake the .qsb files.

    python3 deck/shaders/fsrcnnx.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'FSRCNNX_x2_8-0-4-1.glsl')
QML = os.path.join(HERE, '..', 'Fsrcnnx.qml')
LUMA = 'vec3(0.2126, 0.7152, 0.0722)'


def passes(text):
    for block in text.split('//!HOOK')[1:]:
        lines = ('//!HOOK' + block).splitlines()
        meta = {'BIND': []}
        body = []
        for line in lines:
            m = re.match(r'//!(\w+)\s*(.*)', line)
            if m and not body:
                key, value = m.groups()
                if key == 'BIND':
                    meta['BIND'].append(value.strip())
                else:
                    meta[key] = value.strip()
            elif line.strip() or body:
                body.append(line)
        yield meta, '\n'.join(body).rstrip() + '\n'


def frag(n, meta, body):
    samplers, defines = [], []
    for i, name in enumerate(meta['BIND']):
        if name == 'LUMA':
            samplers.append('layout(binding = %d) uniform sampler2D source;' % (i + 1))
            defines.append('#define LUMA_texOff(o) vec4(dot(texture(source, qt_TexCoord0 + pt * (o)).rgb, %s))' % LUMA)
        else:
            samplers.append('layout(binding = %d) uniform sampler2D %s;' % (i + 1, name.lower()))
            defines.append('#define %s_texOff(o) texture(%s, qt_TexCoord0 + pt * (o))' % (name, name.lower()))
    return '\n'.join([
        '#version 440',
        '// FSRCNNX pass %d, %s: generated by fsrcnnx.py from' % (n, meta.get('DESC', '')),
        '// FSRCNNX_x2_8-0-4-1.glsl, (c) 2017-2021 igv, LGPL-3.0. Do not edit.',
        '',
        'layout(location = 0) in vec2 qt_TexCoord0;',
        'layout(location = 0) out vec4 fragColor;',
        'layout(std140, binding = 0) uniform buf {',
        '    mat4 qt_Matrix;',
        '    float qt_Opacity;',
        '    vec2 pt;',
        '};',
        *samplers,
        *defines,
        '',
        body,
        'void main() { fragColor = hook(); }',
        '',
    ])


def qml(stages):
    out = ['// Generated by shaders/fsrcnnx.py from FSRCNNX_x2_8-0-4-1.glsl',
           '// ((c) 2017-2021 igv, LGPL-3.0). Do not edit; run the script.',
           '//',
           '// FSRCNNX-8: the frame (`source`, `inSize` device pixels) in, its 2x',
           '// (`result`) out. Every pass renders only while `active`.',
           'import QtQuick',
           '',
           'Item {',
           '    id: net',
           '    property bool active: false',
           '    property variant source: null',
           '    property size inSize: Qt.size(1, 1)',
           '    property real dpr: 1',
           '    readonly property size outSize: Qt.size(inSize.width * 2, inSize.height * 2)',
           '    readonly property size pt: Qt.size(1 / inSize.width, 1 / inSize.height)',
           '    readonly property variant result: result',
           '']
    latest = {}
    for n, (meta, _) in enumerate(stages):
        props = []
        for name in meta['BIND']:
            if name == 'LUMA':
                props.append('property variant source: net.source')
            else:
                props.append('property variant %s: t%02d' % (name.lower(), latest[name]))
        out += [
            '    // %d: %s' % (n, meta.get('DESC', '')),
            '    ShaderEffect {',
            '        id: p%02d' % n,
            '        visible: net.active; blending: false',
            '        width: net.inSize.width / net.dpr; height: net.inSize.height / net.dpr',
            *('        ' + p for p in props),
            '        property size pt: net.pt',
            '        fragmentShader: "shaders/fsrcnnx_%02d.frag.qsb"' % n,
            '    }',
            '    ShaderEffectSource {',
            '        id: t%02d' % n,
            '        sourceItem: net.active ? p%02d : null; hideSource: true; visible: false' % n,
            '        textureSize: net.inSize; format: ShaderEffectSource.RGBA16F; smooth: false',
            '    }',
        ]
        latest[meta['SAVE']] = n
    out += [
        '    // the aggregation, with the frame\'s own colour put back',
        '    ShaderEffect {',
        '        id: compose',
        '        visible: net.active; blending: false',
        '        width: net.outSize.width / net.dpr; height: net.outSize.height / net.dpr',
        '        property variant subconv1: t%02d' % latest['SUBCONV1'],
        '        property variant source: net.source',
        '        property size lumaSize: net.inSize',
        '        property size pt: net.pt',
        '        fragmentShader: "shaders/fsrcnnx_compose.frag.qsb"',
        '    }',
        '    ShaderEffectSource {',
        '        id: result',
        '        sourceItem: net.active ? compose : null; hideSource: true; visible: false',
        '        textureSize: net.outSize; format: ShaderEffectSource.RGBA16F; smooth: true',
        '    }',
        '}',
        '']
    return '\n'.join(out)


def main():
    with open(SOURCE) as f:
        found = list(passes(f.read()))
    stages = [(m, b) for m, b in found if 'SAVE' in m]
    assert len(stages) == 13 and found[-1][0].get('DESC') == 'aggregation', 'not the FSRCNNX-8 this was written for'
    for n, (meta, body) in enumerate(stages):
        with open(os.path.join(HERE, 'fsrcnnx_%02d.frag' % n), 'w') as f:
            f.write(frag(n, meta, body))
    with open(QML, 'w') as f:
        f.write(qml(stages))


if __name__ == '__main__':
    main()
