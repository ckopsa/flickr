#!/usr/bin/env python3
"""ArtCNN for Qt Quick: Artoriuz's mpv shader, made into ShaderEffect passes.

ArtCNN_C4F16_DS.glsl (MIT, (c) 2024 Joao Chrisostomo, Kacper Michajłow) is
a small trained network over luma, trained to denoise and sharpen as it
doubles: a 3x3 convolution from luma to sixteen channels, five more 16 to
16 (ReLU on the middle four), a skip back to the first, a convolution to
the four sub-pixels of each texel, then depth-to-space.

mpv runs it as compute shaders. Each layer's sixteen channels live in one
texture at 2x, four RGBA texels per frame texel, and one invocation writes
all four. Qt Quick has no compute in a ShaderEffect, and a fragment writes
one texel, so here each layer is FOUR passes at the frame's own size, one
per group of four channels (`resultG`, the texel at (G % 2, G / 2) in mpv's
tile), each reading the last layer's four groups through samplers one
texel `pt` apart. The arithmetic is the same; the weights are read out of
the hook file, never retyped. This writes

  * artcnn_LL_G.frag — layer LL, group G; and artcnn_06.frag, the layer
    that adds the skip and makes the four sub-pixels.
  * ../Artcnn.qml — the passes wired in order through RGBA16F
    ShaderEffectSources, the same face Fsrcnnx.qml has.

The depth-to-space is artcnn_compose.frag, written by hand: it is also
where the colour comes back. Run build.sh afterwards to bake the .qsb files.

    python3 deck/shaders/artcnn.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'ArtCNN_C4F16_DS.glsl')
QML = os.path.join(HERE, '..', 'Artcnn.qml')
LUMA = 'vec3(0.2126, 0.7152, 0.0722)'
HEADER = '// ArtCNN_C4F16_DS.glsl, (c) 2024 Joao Chrisostomo, Kacper Michajłow, MIT. Do not edit.'


def layers(text):
    """Each compute pass: its DESC, BINDs, and per result its start and terms."""
    for block in text.split('//!DESC')[1:]:
        desc = block.splitlines()[0].strip()
        binds = re.findall(r'^//!BIND (\S+)', block, re.M)
        if 'Depth-To-Space' in desc:
            yield {'desc': desc, 'binds': binds, 'space': True}
            continue
        start = dict(re.findall(r'V4 result(\d) = (V4\([^;]*\));', block))
        terms = {g: [] for g in start}
        for g, expr, c, x, y in re.findall(r'result(\d) \+= (.*?) \* inp_(\d+)_(\d)_(\d);', block):
            terms[g].append((expr, int(c), int(x) - 1, int(y) - 1))
        yield {'desc': desc, 'binds': binds, 'start': start, 'terms': terms,
               'relu': 'max(result0, V4(0.0))' in block}


def glsl(expr):
    return expr.replace('M4(', 'mat4(').replace('V4(', 'vec4(')


def frag(name, desc, inputs, skip, start, terms, relu):
    """One group's pass. `inputs` are the samplers of the layer before (or
    the frame, for the first); `skip` the first layer's, added to them."""
    lines = ['#version 440',
             '// ArtCNN pass %s, %s: generated by artcnn.py from' % (name, desc),
             HEADER, '',
             'layout(location = 0) in vec2 qt_TexCoord0;',
             'layout(location = 0) out vec4 fragColor;',
             'layout(std140, binding = 0) uniform buf {',
             '    mat4 qt_Matrix;',
             '    float qt_Opacity;',
             '    vec2 pt;',
             '};']
    samplers = ['source'] if inputs is None else inputs + (skip or [])
    for i, s in enumerate(samplers):
        lines.append('layout(binding = %d) uniform sampler2D %s;' % (i + 1, s))
    lines += ['', 'void main()', '{']
    taps = sorted({(c, x, y) for _, c, x, y in terms})
    for c, x, y in taps:
        at = 'qt_TexCoord0 + pt * vec2(%d.0, %d.0)' % (x, y)
        if inputs is None:
            lines.append('    float inp_%d_%d_%d = dot(texture(source, %s).rgb, %s);' % (c, x + 1, y + 1, at, LUMA))
        elif skip:
            lines.append('    vec4 inp_%d_%d_%d = texture(%s, %s) + texture(%s, %s);'
                         % (c, x + 1, y + 1, inputs[c], at, skip[c], at))
        else:
            lines.append('    vec4 inp_%d_%d_%d = texture(%s, %s);' % (c, x + 1, y + 1, inputs[c], at))
    lines.append('    vec4 result = %s;' % glsl(start))
    for expr, c, x, y in terms:
        lines.append('    result += %s * inp_%d_%d_%d;' % (glsl(expr), c, x + 1, y + 1))
    lines.append('    fragColor = %s;' % ('max(result, vec4(0.0))' if relu else 'result'))
    lines += ['}', '']
    return '\n'.join(lines)


def effect(pid, shader, props, size):
    return ['    ShaderEffect {',
            '        id: p%s' % pid,
            '        visible: net.active; blending: false',
            '        width: net.%s.width / net.dpr; height: net.%s.height / net.dpr' % (size, size),
            *('        ' + p for p in props),
            '        property size pt: net.pt',
            '        fragmentShader: "shaders/%s.frag.qsb"' % shader,
            '    }']


def capture(pid, size, smooth='false'):
    return ['    ShaderEffectSource {',
            '        id: t%s' % pid,
            '        sourceItem: net.active ? p%s : null; hideSource: true; visible: false' % pid,
            '        textureSize: net.%s; format: ShaderEffectSource.RGBA16F; smooth: %s' % (size, smooth),
            '    }']


def main():
    with open(SOURCE) as f:
        found = list(layers(f.read()))
    assert len(found) == 8 and found[-1].get('space') and found[6]['binds'] == ['conv2d', 'conv2d_5'], \
        'not the ArtCNN C4F16 this was written for'

    qml = ['// Generated by shaders/artcnn.py from ArtCNN_C4F16_DS.glsl',
           '// ((c) 2024 Joao Chrisostomo, Kacper Michajłow, MIT). Do not edit; run the script.',
           '//',
           '// ArtCNN C4F16 DS: the frame (`source`, `inSize` device pixels) in, its',
           '// 2x (`result`) out, denoised and sharpened. Renders only while `active`.',
           'import QtQuick', '',
           'Item {',
           '    id: net',
           '    property bool active: false',
           '    property variant source: null',
           '    property size inSize: Qt.size(1, 1)',
           '    property real dpr: 1',
           '    readonly property size outSize: Qt.size(inSize.width * 2, inSize.height * 2)',
           '    readonly property size pt: Qt.size(1 / inSize.width, 1 / inSize.height)',
           '    readonly property variant result: result', '']
    groups = lambda n: ['l%d_%d' % (n, g) for g in range(4)]
    for n, layer in enumerate(found[:6]):
        prev = None if n == 0 else groups(n - 1)
        qml.append('    // %d: %s, four groups of four channels' % (n, layer['desc']))
        for g in range(4):
            name = '%02d_%d' % (n, g)
            with open(os.path.join(HERE, 'artcnn_%s.frag' % name), 'w') as f:
                f.write(frag(name, layer['desc'], prev, None, layer['start'][str(g)],
                             layer['terms'][str(g)], layer['relu']))
            props = (['property variant source: net.source'] if prev is None
                     else ['property variant %s: t%s' % (s, s[1:]) for s in prev])
            pid = '%d_%d' % (n, g)
            qml += effect(pid, 'artcnn_' + name, props, 'inSize') + capture(pid, 'inSize')

    last = found[6]
    with open(os.path.join(HERE, 'artcnn_06.frag'), 'w') as f:
        f.write(frag('06', last['desc'], groups(5), groups(0), last['start']['0'], last['terms']['0'], False))
    props = ['property variant %s: t%s' % (s, s[1:]) for s in groups(5) + groups(0)]
    qml.append('    // 6: %s, the skip added; four sub-pixels a texel' % last['desc'])
    qml += effect('6', 'artcnn_06', props, 'inSize') + capture('6', 'inSize')

    qml += ['    // depth-to-space, with the frame\'s own colour put back',
            '    ShaderEffect {',
            '        id: compose',
            '        visible: net.active; blending: false',
            '        width: net.outSize.width / net.dpr; height: net.outSize.height / net.dpr',
            '        property variant subpixels: t6',
            '        property variant source: net.source',
            '        property size lumaSize: net.inSize',
            '        property size pt: net.pt',
            '        fragmentShader: "shaders/artcnn_compose.frag.qsb"',
            '    }',
            '    ShaderEffectSource {',
            '        id: result',
            '        sourceItem: net.active ? compose : null; hideSource: true; visible: false',
            '        textureSize: net.outSize; format: ShaderEffectSource.RGBA16F; smooth: true',
            '    }',
            '}', '']
    with open(QML, 'w') as f:
        f.write('\n'.join(qml))


if __name__ == '__main__':
    main()
